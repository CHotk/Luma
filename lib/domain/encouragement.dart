  /// 取某一天要顯示的句子。
  ///
  /// [date] 只看年月日，同一天不管開幾次都一樣。
  static String forDate(DateTime date) {
    final n = lines.length;
    final day = _dayNumber(date);
    final cycle = day ~/ n; // 第幾輪
    final position = day % n; // 這一輪的第幾天

    // 每一輪用輪次當種子重新洗牌，所以順序每輪都不同，
    // 但同一輪之內不會有任何一句重複出現。
    final order = List.generate(n, (i) => i)..shuffle(Random(cycle));
    return lines[order[position]];
  }

  /// 從一個固定的日子算起是第幾天。只取年月日，不受時分秒影響。
  static int _dayNumber(DateTime date) {
    final today = DateTime(date.year, date.month, date.day);
    return today.difference(DateTime(2026, 1, 1)).inDays;
  }
}
